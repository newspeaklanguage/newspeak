/* Package a PLAIN JS deploy of the IDE from a headless psoup IDE, then boot the
   result and see whether it starts.

     croquet-probes/run.sh js-deploy-boot-probe.js
     croquet-probes/run.sh NS_SNAPSHOT=HopscotchWebIDE-JSTEST.vfuel js-deploy-boot-probe.js

   Why this exists: a JS deployment is generated by MirrorsForJS running inside
   the psoup IDE, and the generated image then runs MirrorsForJS again at its own
   startup. Neither path is exercised by building a vfuel or by booting the psoup
   IDE, so a fault confined to MirrorsForJS ships looking perfectly healthy --
   which is what happened on 2026-09-20, when keying a member sort by `selector`
   (understood by IntermediateMethod, but not by the MethodMirror/MethodBuilder
   pair this module handles) left the deployed IDE dead on arrival while psoup
   was fine.

   Artifacts are staged under out/JSBootTest.* so the real HopscotchWebIDE.js is
   never touched. Needs the local server on :8080 serving out/. */
const { spawn } = require('child_process');
const http = require('http');
const fs = require('fs');
const WebSocket = require('ws');

const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const OUT = '/Users/gbracha/newspeak/dev/web/newspeak/out/';
const PORT = 9476;
const SNAPSHOT = process.env.NS_SNAPSHOT || 'HopscotchWebIDE-JSTEST.vfuel';
const IDE_URL = `http://localhost:8080/primordialsoup.html?snapshot=${SNAPSHOT}`;
const NAME = 'JSBootTest';

// Package the IDE and park the pieces on window.
//
// RuntimeWithMirrorBuilders, not Runtime: an IDE compiles code, so it needs the
// mirror BUILDERS. Packaging it against the plain RuntimeForJS produces a bundle
// that dies at startup with a bare doesNotUnderstand -- which cost a long
// detour on 2026-09-20, because it looks exactly like a fault in whatever you
// happen to have changed.
const DOIT =
  "[:d | platform js global at: #depPage put: d page. " +
  "platform js global at: #depScript put: d script. " +
  "platform js global at: #depSources put: d sources. 'PACKAGED-OK'] value: " +
  "((ide deployment jsPackagerForPlatform: platform) " +
  "packageApplicationConfiguration: (ide namespacing Root at: #HopscotchWebIDE) " +
  "withRuntimeConfiguration: ide deployment RuntimeWithMirrorBuilders " +
  "usingNamespace: ide namespacing Root)";

const sleep = ms => new Promise(r => setTimeout(r, ms));
function getJson(path) {
  return new Promise((res, rej) => {
    http.get({ host: '127.0.0.1', port: PORT, path }, r => {
      let b = ''; r.on('data', c => b += c);
      r.on('end', () => { try { res(JSON.parse(b)); } catch (e) { rej(e); } });
    }).on('error', rej);
  });
}

async function attach(url) {
  let page;
  for (let i = 0; i < 100 && !page; i++) {
    try { const t = await getJson('/json'); page = t && t.find(x => x.type === 'page'); } catch (e) {}
    await sleep(300);
  }
  const ws = new WebSocket(page.webSocketDebuggerUrl, { perMessageDeflate: false, maxPayload: 256 * 1024 * 1024 });
  await new Promise(r => ws.on('open', r));
  let id = 0; const pending = new Map(); const log = [];
  ws.on('message', raw => {
    try {
      const m = JSON.parse(raw);
      if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); return; }
      if (m.method === 'Runtime.consoleAPICalled') {
        log.push('[' + m.params.type + '] ' + m.params.args
          .map(x => x.value !== undefined ? String(x.value) : (x.description || x.type)).join(' '));
      } else if (m.method === 'Runtime.exceptionThrown') {
        const d = m.params.exceptionDetails || {};
        // The frame names carry the Newspeak receiver class and selector,
        // e.g. MirrorsForJS`MethodBuilder.$doesNotUnderstand$ -- without them
        // a DNU says only that something did not understand something.
        const frames = ((d.stackTrace || {}).callFrames || [])
          .slice(0, 8).map(f => f.functionName || '(anon)').join(' <- ');
        log.push('[exception] ' + d.text + ' ' + ((d.exception || {}).description || '')
                 + '\n      frames: ' + frames);
      }
    } catch (e) {}
  });
  const send = (m, p) => new Promise(res => { const mid = ++id; pending.set(mid, res); ws.send(JSON.stringify({ id: mid, method: m, params: p || {} })); });
  await send('Runtime.enable');
  const ev = async e => { const r = await send('Runtime.evaluate', { expression: e, returnByValue: true }); return r && r.result && r.result.value; };
  await send('Page.navigate', { url });
  return { ev, log, send };
}

async function main() {
  const chrome = spawn(CHROME, ['--headless=new', `--remote-debugging-port=${PORT}`,
    '--remote-allow-origins=*', '--user-data-dir=/tmp/ns-jsboot', '--no-first-run', '--disable-gpu',
    '--disable-background-timer-throttling', '--disable-renderer-backgrounding', 'about:blank'], { stdio: 'ignore' });
  process.on('exit', () => { try { chrome.kill(); } catch (e) {} });

  console.log(`booting the psoup IDE (${SNAPSHOT}) to do the packaging …`);
  const ide = await attach(IDE_URL);
  for (let i = 0; i < 120; i++) {
    const t = await ide.ev('document.body?document.body.innerText:""');
    if (typeof t === 'string' && (t.includes('Workspaces') || t.includes('backup changes'))) break;
    await sleep(1500);
  }
  if (await ide.ev("document.body.innerText.includes('backup changes')")) {
    await ide.ev(`(function(){var m=Array.from(document.querySelectorAll('a,button,span,div,label')).filter(e=>(e.innerText||'').trim().indexOf('Use current version')===0);var e=m[m.length-1];['mousedown','mouseup','click'].forEach(t=>e.dispatchEvent(new MouseEvent(t,{bubbles:true,cancelable:true,view:window})));return 'x'})()`);
    for (let i = 0; i < 40; i++) { if (await ide.ev("document.body.innerText.includes('Workspaces')")) break; await sleep(1500); }
  }
  await sleep(3000);
  await ide.ev(`(function(){var m=Array.from(document.querySelectorAll('a,button,span,div,label')).filter(e=>(e.innerText||'').trim()==='Workspaces');var e=m[m.length-1];['mousedown','mouseup','click'].forEach(t=>e.dispatchEvent(new MouseEvent(t,{bubbles:true,cancelable:true,view:window})));return 'x'})()`);
  for (let i = 0; i < 30; i++) { if (await ide.ev("document.body.innerText.includes('Evaluate Selection')")) break; await sleep(1000); }
  await sleep(2000);

  console.log('packaging a plain JS deploy …');
  await ide.ev(`(function(){var cms=document.querySelectorAll('.CodeMirror');var cm=cms[cms.length-1].CodeMirror;cm.focus();cm.setValue(${JSON.stringify(DOIT)});cm.execCommand('selectAll');return 'SET'})()`);
  await sleep(1500);
  await ide.ev(`(function(){var m=Array.from(document.querySelectorAll('a,button,span,div,label')).filter(e=>(e.innerText||'').trim().indexOf('Evaluate Selection')===0);var e=m[m.length-1];['mousedown','mouseup','click'].forEach(t=>e.dispatchEvent(new MouseEvent(t,{bubbles:true,cancelable:true,view:window})));return 'x'})()`);

  let script = null;
  for (let i = 0; i < 120; i++) {
    await sleep(2000);
    script = await ide.ev('window.depScript ? window.depScript.length : 0');
    if (script) break;
    const bad = ide.log.filter(l => /doesNotUnderstand|MessageNotUnderstood|exception/i.test(l));
    if (bad.length) {
      console.log('\nFAIL: packaging itself blew up:');
      bad.slice(0, 6).forEach(l => console.log('  ' + l.slice(0, 300)));
      process.exit(1);
    }
  }
  if (!script) {
    console.log('\nFAIL: packaging produced no script within the deadline.');
    const text = await ide.ev('document.body ? document.body.innerText.slice(0, 1200) : ""');
    console.log('--- what the IDE is showing ---\n' + text);
    console.log('--- last console lines ---');
    ide.log.slice(-12).forEach(l => console.log('  ' + l.slice(0, 200)));
    process.exit(1);
  }
  console.log(`packaged: script is ${script} chars`);

  // The packager names the artifacts after the app class, and bakes those
  // names into the page. Renaming the files without rewriting the references
  // leaves the page loading the REAL HopscotchWebIDE.js -- which is what
  // happened first time round, so the probe booted the very bundle it was
  // supposed to be replacing and reported its build time.
  for (const [k, f] of [['depPage', NAME + '.html'], ['depScript', NAME + '.js'],
                        ['depSources', NAME + '.sources.js']]) {
    let text = await ide.ev(`window.${k} || ''`);
    if (k === 'depPage') {
      text = text.split('HopscotchWebIDE.sources.js').join(NAME + '.sources.js')
                 .split('HopscotchWebIDE.js').join(NAME + '.js');
      if (text.includes('HopscotchWebIDE.js')) {
        console.log('\nFAIL: could not repoint the page away from the real bundle.');
        process.exit(1);
      }
    }
    fs.writeFileSync(OUT + f, text);
    console.log(`  wrote out/${f} (${text.length} chars)`);
  }

  console.log(`\nbooting the generated JS IDE …`);
  const js = await attach(`http://localhost:8080/${NAME}.html`);
  let rendered = 0;
  for (let i = 0; i < 40; i++) {
    await sleep(1000);
    rendered = await js.ev('document.body ? document.body.innerText.length : 0') || 0;
    if (rendered > 40) break;
  }
  const bad = js.log.filter(l => /doesNotUnderstand|MessageNotUnderstood|\[error\]|exception/i.test(l));
  console.log(`rendered ${rendered} chars of text`);
  if (bad.length) {
    console.log('\nFAIL: the deployed JS IDE reported trouble while starting:');
    bad.slice(0, 8).forEach(l => console.log('  ' + l.slice(0, 300)));
    process.exit(1);
  }
  if (rendered <= 40) {
    console.log('\nFAIL: the deployed JS IDE rendered nothing.');
    js.log.slice(-8).forEach(l => console.log('  ' + l.slice(0, 300)));
    process.exit(1);
  }
  const stamp = await js.ev('String(globalThis.nsBuildTime)');
  const shown = await js.ev("(document.body.innerText.match(/[^\\n]*built[^\\n]*/)||[''])[0]");
  console.log(`nsBuildTime in the bundle: ${stamp}`);
  console.log(`version on its home page : ${shown}`);
  // Reported, not asserted: nothing stamps a deployment with its own instant
  // yet, so a bundle inheriting the generating image's date is the expected
  // state until the packager is adjusted.
  
  console.log('\nPASS: the JS deploy was packaged and the deployed IDE started.');
  process.exit(0);
}

main().catch(e => { console.log('BAIL: ' + e.message); process.exit(2); });
